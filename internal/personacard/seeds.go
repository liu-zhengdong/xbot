func ensureDefault(dir string) error {
	raw, err := os.ReadFile(filepath.Join(dir, defaultFile))
	if err == nil {
		if _, err := read(dir, strings.TrimSpace(string(raw))); err == nil {
			return nil
		}
	}
	cards, err := list(dir)
	if err != nil {
		return err
	}
	id := ""
	for _, c := range cards {
		if c.Name == DefaultName {
			id = c.ID
			break
		}
	}
	if id == "" {
		id = newID()
		if _, err := write(dir, id, DefaultName, PartnerPersona); err != nil {
			return err
		}
	}
	return fsutil.WriteAtomic(filepath.Join(dir, defaultFile), []byte(id+"\n"), 0600)
}

// EnsureSeeds fills a never-used empty library, or upgrades unchanged old seeds
// in a marked library, then makes sure the library has its default card. All
// writes use the library lock, including across processes. A marked empty
// library gets only the default card; a failed first seed run removes its own cards.
func EnsureSeeds(root string) error {
	if err := ensureSeeds(root); err != nil {
		return err
	}
	if _, ok := Default(root); ok {
		return nil
	}
	return locked(root, ensureDefault)
}

func ensureSeeds(root string) error {
	dir, err := open(root)
	if err != nil {
		return err
	}
	if has(dir, seededFile) {
		return locked(root, upgradeSeeds)
	}
	cards, err := list(dir)
	if err != nil {
		return err
	}
	if len(cards) > 0 && !has(dir, ".lock") {
		return nil
	}
	return locked(root, func(dir string) error {
		if has(dir, seededFile) {
			return upgradeSeeds(dir)
		}
		if cards, err := list(dir); err != nil || len(cards) > 0 {
			return err
		}
		var ids []string
		err := func() error {
			// The list is newest first; step the times back so the seeds keep their order.
			now := time.Now()
			for i, s := range Seeds {
				if beforeSeed != nil {
					beforeSeed(i)
				}
				name, body, err := clean(s.Name, s.Body)
				if err != nil {
					return err
				}
				id := newID()
				ids = append(ids, id)
				if _, err := write(dir, id, name, body); err != nil {
					return err
				}
				t := now.Add(-time.Duration(i) * time.Second)
				_ = os.Chtimes(filepath.Join(dir, id, "card.md"), t, t)
			}
			return markSeeded(dir)
		}()
		if err != nil {
			for _, id := range ids {
				_ = os.RemoveAll(filepath.Join(dir, id))
			}
		}
		return err
	})
}

// upgradeSeeds runs under the library lock, so an Update cannot slip between the
// comparison and write. Keep successful upgrades if another card fails; retry only
// unchanged old cards on the next call. list skips unreadable cards as usual.
func upgradeSeeds(dir string) error {
	cards, err := list(dir)
	if err != nil {
		return err
	}
	var errs []error
	for _, c := range cards {
		if c.Body != legacySeedBodies[c.Name] && !slices.Contains(legacyOwnerBodies[c.Name], c.Body) {
			continue
		}
		for _, s := range Seeds {
			if s.Name != c.Name || c.Body == s.Body {
				continue
			}
			name, body, err := clean(c.Name, s.Body)
			if err == nil {
				_, err = write(dir, c.ID, name, body)
			}
			if err != nil {
				errs = append(errs, fmt.Errorf("personacard: upgrade %s: %w", c.ID, err))
			}
			break
		}
	}
	return errors.Join(errs...)
}
